import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true,executablePath:'C:/Users/Administrator/AppData/Local/ms-playwright/chromium-1208/chrome-win64/chrome.exe',args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const checks=[],errors=[];
const assert=(value,name)=>{if(!value)throw Error(name);checks.push(name);};
try {
  const page=await browser.newPage({viewport:{width:1440,height:928}});
  page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto('http://127.0.0.1:4318/');await page.waitForFunction(()=>window.__radar?.renderedFrames>2);
  const copy=await page.locator('.hero-copy').boundingBox(),viewer=await page.locator('.farm-viewer').boundingBox();
  assert(viewer.x>copy.x+copy.width,'3D farm sits to the right of introduction');
  assert(await page.locator('.regions,.site-footer,.hero-note,.secondary-link,.model-caption,.site-header nav').count()===0,'homepage removes repeated navigation and decorative content');
  assert(await page.locator('[data-scene]').count()===10,'ten scenes have one shared navigation');
  assert(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight+1),'desktop homepage fits one screen');
  await page.locator('#pause').click();await page.waitForTimeout(500);
  await page.locator('.view-buttons [data-view="terrace"]').click();
  await page.waitForFunction(()=>window.__radar.view.moving);
  await page.waitForFunction(()=>!window.__radar.view.moving);
  const terrace=await page.evaluate(()=>window.__radar.view);
  assert(Math.hypot(...terrace.target.map((v,i)=>v-[3.2,1,-3.3][i]))<.00001,'terrace preset reaches correct target while paused');
  await page.screenshot({path:'verification/farm-website-terrace.png'});
  await page.locator('.view-buttons [data-view="buildings"]').click();
  await page.waitForFunction(()=>window.__radar.view.moving&&window.__radar.view.target[0]<2);
  await page.locator('.view-buttons [data-view="orchard"]').click();
  await page.waitForFunction(()=>!window.__radar.view.moving);
  assert(await page.evaluate(()=>window.__radar.view.name==='orchard'&&Math.abs(window.__radar.view.target[2]-4.5)<.00001),'new preset redirects an unfinished flight');
  await page.locator('.view-buttons [data-view="terrace"]').click();
  await page.waitForFunction(()=>window.__radar.view.moving);
  const viewport=await page.locator('#viewport').boundingBox();
  await page.mouse.move(viewport.x+viewport.width*.6,viewport.y+viewport.height*.45);await page.mouse.down();await page.mouse.move(viewport.x+viewport.width*.55,viewport.y+viewport.height*.47,{steps:4});await page.mouse.up();
  assert(await page.evaluate(()=>window.__radar.view.name==='free'&&!window.__radar.view.moving),'manual drag interrupts camera flight');
  await page.locator('#next-model').click();await page.waitForFunction(()=>window.__radar.active===1&&window.__radar.morphProgress===1);
  assert(await page.locator('#hero-title').innerText().then(text=>text.includes('每一滴水')),'homepage call to action switches to water model');
  await page.locator('.model-buttons [data-scene="0"]').click();await page.waitForFunction(()=>window.__radar.active===0&&window.__radar.morphProgress===1);
  await page.locator('.view-buttons [data-view="overview"]').click();await page.waitForFunction(()=>!window.__radar.view.moving);
  await page.evaluate(()=>window.scrollTo(0,0));await page.waitForTimeout(350);
  await page.screenshot({path:'verification/farm-website-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>window.scrollTo(0,0));await page.waitForTimeout(350);
  const mobileCopy=await page.locator('.hero-copy').boundingBox(),mobileViewer=await page.locator('.farm-viewer').boundingBox();
  assert(mobileViewer.y>=mobileCopy.y+mobileCopy.height,'mobile introduction and viewer stack vertically');
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'complete mobile webpage has no horizontal overflow');
  await page.screenshot({path:'verification/farm-website-mobile.png',fullPage:true});
  const reduced=await browser.newPage({reducedMotion:'reduce'});await reduced.goto('http://127.0.0.1:4318/');await reduced.waitForFunction(()=>window.__radar);
  await reduced.locator('.view-buttons [data-view="orchard"]').click();
  assert(await reduced.evaluate(()=>!window.__radar.view.moving&&window.__radar.view.name==='orchard'),'reduced motion uses an immediate camera change');
  assert(errors.length===0,'no website interaction errors');
  await fs.writeFile('verification/website-results.json',JSON.stringify({checks,errors},null,2));console.log(JSON.stringify({checks:checks.length,errors}));
} finally {await browser.close();}
